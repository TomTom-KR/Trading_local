            _venue("XASX", "Sydney", "Australia/Sydney", "ASIA", ((time(10, 0), time(16, 0)),)),
            # Europe
            _venue("XETR", "Xetra", "Europe/Berlin", "EU", _DAY_0900_1730),
            _venue("XFRA", "Frankfurt", "Europe/Berlin", "EU", _DAY_0900_1730),  # Xetra-aligned (module docstring)
