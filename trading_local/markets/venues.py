"""Venue table of the trading calendar plus the override data that corrects exchange_calendars.

Sources (research probe of 2026-11-22, cross-checked against the exchanges' own calendars):
exchange_hours.json (regular hours, pre/post windows), holidays_researched.json (closures and early
closes 2026-11-23..2027-12-31) and calendar_crosscheck*.json (library versus official data).
exchange_calendars 4.13.3 matches the official data for XNYS/XNAS, XETR, XFRA, XLON, XPAR, XAMS, XSWX,
XCSE, XTKS, XHKG and XASX including all early closes. Where it is incomplete, the tables at the end of
this module fill the gap (``EXTRA_CLOSURES``, ``RESEARCHED_CLOSURES``), and ``Venue.library_from`` /
``Venue.library_until`` keep every request inside the library's data range.

Deliberate modelling choices
* XFRA: Boerse Frankfurt's specialist floor quotes shares 08:00-22:00, but we keep the Xetra-aligned
  09:00-17:30 session of the library's XFRA calendar as the regular session: liquidity and the cost
  model (about 2 bp spread) only hold in Xetra hours, so signals and fills stay inside them.
* US venues: only the regular session 09:30-16:00 New York time counts as open. Pre-market and
  after-hours windows are informational, and the 23x5 overnight session of NYSE Arca / Nasdaq announced
  from 2026-12-06 is NOT modelled (no signals, no fills overnight).
* XNSE uses the library's XBOM (BSE) calendar and XSHE the XSHG calendar: same hours and holidays.
* Pseudo venues CRYPTO / KRAKEN / FX / CME are generated by rule. Their trading date is the UTC date (see
  ``contracts.MarketCalendar``), so their ``timezone`` is 'UTC'; the rule times are New York times.
  KRAKEN (the crypto exchange Kraken, real-time public data) trades 24/7 exactly like CRYPTO (Yahoo's crypto
  quotes): one regular segment per UTC day, never part of the session overview (region GLOBAL).
"""

from collections.abc import Mapping
from dataclasses import dataclass
from datetime import date, time
from types import MappingProxyType
from typing import Final, Literal

from trading_local.models import Region

# How a venue's sessions are produced:
#   library      exchange_calendars (``library_code``) + override tables of this module
#   always_open  24/7, one segment per UTC day
#   fx_week      continuous from Sunday 17:00 to Friday 17:00 New York time
#   globex_week  CME Globex: Sunday 18:00 to Friday 17:00 New York time, daily break 17:00-18:00
VenueRule = Literal["library", "always_open", "fx_week", "globex_week"]


@dataclass(frozen=True, slots=True)
class ExtendedHours:
    """Pre-market / after-hours windows around the regular session, in the venue's local time.

    The pre-market runs from ``pre_start`` to the regular open, the after-hours window from the regular
    close (an early close included) to ``post_end`` - or to ``post_end_after_early_close`` on early-close days.
    """

    pre_start: time
    post_end: time
    post_end_after_early_close: time


@dataclass(frozen=True, slots=True)
class Venue:
    key: str  # calendar key stored in Instrument.exchange
    name_de: str  # German display name
    timezone: str  # IANA zone; 'UTC' for the pseudo venues (their trading date is the UTC date)
    region: Region
    rule: VenueRule
    library_code: str | None = None  # exchange_calendars calendar name (rule 'library'); None: same as key
    # Regular segments of a normal trading day in local time. Used for days without library data
    # (weekday estimate); the library's own hours take precedence wherever it has data.
    regular_hours: tuple[tuple[time, time], ...] = ()
    # Data range of the library calendar (its class methods bound_min / bound_max; it raises for any day
    # outside). Days outside are built from weekdays + regular_hours (+ RESEARCHED_CLOSURES), so one query
    # far in the past or future never costs the library data of the other days. None: unbounded side.
    library_from: date | None = None
    library_until: date | None = None
    extended: ExtendedHours | None = None


_US_EXTENDED: Final = ExtendedHours(pre_start=time(4, 0), post_end=time(20, 0), post_end_after_early_close=time(17, 0))
_DAY_0930_1600: Final = ((time(9, 30), time(16, 0)),)
_DAY_0900_1730: Final = ((time(9, 0), time(17, 30)),)
_CHINA_HOURS: Final = ((time(9, 30), time(11, 30)), (time(13, 0), time(15, 0)))
# Data ranges shared by several bounded calendars of exchange_calendars 4.13.3 (the ranges of all venues
# are pinned to the library's bound_min / bound_max by tests/markets/test_robustness.py).
_LIBRARY_DATA_END_2026: Final = date(2026, 12, 31)  # XSHG and XBOM
_XSHG_FROM: Final = date(1990, 12, 3)
_XTKS_XBOM_FROM: Final = date(1997, 1, 1)


def _venue(
    key: str,
    name_de: str,
    timezone: str,
    region: Region,
    hours: tuple[tuple[time, time], ...],
    *,
    library_code: str | None = None,
    library_from: date | None = None,
    library_until: date | None = None,
    extended: ExtendedHours | None = None,
) -> Venue:
    return Venue(
        key, name_de, timezone, region, "library", library_code=library_code, regular_hours=hours,
        library_from=library_from, library_until=library_until, extended=extended,
    )


# Order matters: it is the order of ``exchanges()`` and of the venues inside each region of the overview.
