# Regions of the session overview, in the order the trading day moves round the globe.
OVERVIEW_REGIONS: Final[tuple[Region, ...]] = ("ASIA", "EU", "US")
REGION_LABELS_DE: Final[Mapping[Region, str]] = MappingProxyType({"ASIA": "Asien", "EU": "Europa", "US": "USA"})

# Rule times of the pseudo venues FX and CME (New York wall-clock time; holidays are ignored).
RULE_TIMEZONE: Final = "America/New_York"
FX_WEEK_OPEN: Final = time(17, 0)  # Sunday
FX_WEEK_CLOSE: Final = time(17, 0)  # Friday
GLOBEX_DAILY_OPEN: Final = time(18, 0)  # Sunday..Thursday; the session runs into the next day
GLOBEX_DAILY_CLOSE: Final = time(17, 0)  # Monday..Friday


def venues_of_region(region: Region) -> tuple[str, ...]:
    """Calendar keys of one region in table order."""
    return tuple(key for key, venue in VENUES.items() if venue.region == region)


# ------------------------------------------------------------------------------------------------
# Override data
# ------------------------------------------------------------------------------------------------
def _dates(*isoformats: str) -> frozenset[date]:
    return frozenset(date.fromisoformat(text) for text in isoformats)


# Weekday closures that exchange_calendars 4.13.3 treats as sessions. Applied on top of the library.
EXTRA_CLOSURES: Final[Mapping[str, frozenset[date]]] = MappingProxyType(
    {
        # Official TWSE holiday API: two 'no trading, clearing only' days before Lunar New Year and two
        # adjusted holidays (Children's Day 04-04 and Constitution Day 12-25 fall on a weekend).
        "XTAI": _dates("2027-02-02", "2027-02-03", "2027-04-06", "2027-12-24"),
        # Constitution Day (17 July) is a Korean public holiday again from 2026: Friday 2026-07-17
        # (reported KRX closure) and the substitute Monday 2027-07-19 (derived; uncertain until KRX
        # publishes its 2027 list in December 2026).
        "XKRX": _dates("2026-07-17", "2027-07-19"),
    }
)

